import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageJson = JSON.parse(
	await readFile(resolve(root, "package.json"), "utf8"),
);
const expectedVersion = packageJson.dependencies?.three;
if (!expectedVersion || !/^\d+\.\d+\.\d+$/.test(expectedVersion)) {
	throw new Error("Pin dependencies.three to an exact version before syncing.");
}

const installedPackage = JSON.parse(
	await readFile(resolve(root, "node_modules", "three", "package.json"), "utf8"),
);
if (installedPackage.version !== expectedVersion) {
	throw new Error(
		`Installed Three.js ${installedPackage.version} does not match pinned ${expectedVersion}.`,
	);
}

const vendorDirectory = resolve(root, "public", "vendor");
await mkdir(vendorDirectory, { recursive: true });
await copyFile(
	resolve(root, "node_modules", "three", "build", "three.module.min.js"),
	resolve(vendorDirectory, "three.module.min.js"),
);
await copyFile(
	resolve(root, "node_modules", "three", "build", "three.core.min.js"),
	resolve(vendorDirectory, "three.core.min.js"),
);
await copyFile(
	resolve(root, "node_modules", "three", "LICENSE"),
	resolve(vendorDirectory, "three.LICENSE.txt"),
);
await writeFile(
	resolve(vendorDirectory, "three.RECEIPT.txt"),
	[
		"Package: three",
		`Version: ${installedPackage.version}`,
		"Source: https://www.npmjs.com/package/three",
		"Project: https://threejs.org/",
		"License: MIT (see three.LICENSE.txt)",
		"Vendored files: build/three.module.min.js, build/three.core.min.js",
		"Generated by: npm run vendor:three",
		"",
	].join("\n"),
	"utf8",
);

console.log(`Synced Three.js ${installedPackage.version} to public/vendor.`);
